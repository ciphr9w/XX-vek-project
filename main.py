# =========================
# ПОЛУЧИТЬ ОДНУ ЭПОХУ
# =========================

@app.get("/api/eras/{era_id}")
def get_era(era_id: int):

    for era in eras:

        if era["id"] == era_id:

            return era


    return {
        "error": "Эпоха не найдена"
    }